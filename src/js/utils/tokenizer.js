// 最大词长
const MAX_WORD_LEN = 5;

/**
 * 正向最大匹配分词
 * @param {string} text - 输入文本
 * @returns {string[]} 分词结果
 */
function tokenize(text) {
  const tokens = [];
  const lower = text.toLowerCase();

  // 提取英文单词
  const engWords = lower.match(/[a-zA-Z]{2,}/g) || [];
  tokens.push(...engWords);

  // 提取中文部分并分词
  const chineseSegments = lower.match(/[\u4e00-\u9fff]+/g) || [];

  for (const segment of chineseSegments) {
    let i = 0;
    while (i < segment.length) {
      let matched = false;
      // 从最长词开始尝试匹配
      for (let len = Math.min(MAX_WORD_LEN, segment.length - i); len >= 2; len--) {
        const word = segment.substring(i, i + len);
        if (DICT.has(word)) {
          tokens.push(word);
          i += len;
          matched = true;
          break;
        }
      }
      if (!matched) {
        // 单字：跳过常见虚词
        const char = segment[i];
        if (!'的了么吗呢啊哦呀吧把被在到和与或'.includes(char)) {
          tokens.push(char);
        }
        i++;
      }
    }
  }

  return [...new Set(tokens)];
}

// 导出
window.tokenize = tokenize;
